"""
Summarizer service — per-chunk LLM summaries + hierarchical (RAPTOR-style) rollup.

What it produces
────────────────
1. LEAF SUMMARIES   — a concise 1-3 sentence abstractive summary for every leaf
                      chunk. Stored on Chunk.summary. Later embedded separately
                      (Chunk.summary_embedding) so retrieval can match on either
                      the verbatim content vector OR the gist vector.

                      Summaries are **category-aware**: each category gets a
                      focused system prompt so the summary is grounded in the
                      right extraction context, producing independent lanes:

                        Content → [Chunk] → [Knowledge] → {Summary:Knowledge}
                          → {summary, content, summary_embedding, content_embedding}
                        Content → [Chunk] → [Keyword]   → {Summary:Keyword}
                          → {summary, keyword, summary_embedding, keyword_embedding}
                        Content → [Chunk] → [Persona]   → {Summary:Persona}
                          → {summary, persona, summary_embedding, persona_embedding}
                        Content → [Chunk] → [Workflow]  → {Summary:Workflow}
                          → {summary, workflow, summary_embedding, workflow_embedding}
                      (features and entities follow the same shape)

2. ROLLUP SUMMARIES — walking the existing parent→child tree bottom-up, each
                      branch node's summary is generated by summarizing its
                      children's summaries. This fills the branch chunks (which
                      the old chunker left as "first paragraph" stubs) with real
                      synthesized gist, and gives you the N-level summary tree
                      the design calls for — one summary per node, parent = the
                      summary of its children.

3. CATEGORY / DOC OVERVIEW — the top of the rollup: a summary of the roots'
                      summaries per category, and one document-level
                      "summary of summaries". This is what feeds the *_OVERVIEW
                      markdown, as opposed to the raw per-type summary dumps.

Design notes
────────────
- Reuses the existing LLMService (IBM AIM via curl) through a single added
  method, `complete_batch`, so all the TLS/curl handling lives in one place.
- Every LLM path has a deterministic extractive fallback (first-sentence(s))
  so the pipeline still completes with LLM_ENABLED=false.
- Batched + concurrent: leaf summaries are chunked into batches and fired
  through the provider's existing concurrency-bounded gather.
- Per-category passes are batched independently so a single
  complete_batch() call per category keeps the rate-limit behaviour
  consistent with the rest of the pipeline.
"""
from __future__ import annotations

import re
from collections import defaultdict
from typing import Optional

from src.models import Chunk
from src.utils.logging import get_logger

logger = get_logger(__name__)

